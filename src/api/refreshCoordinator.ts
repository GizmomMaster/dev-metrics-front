/**
 * Координатор обновления access-токена.
 *
 * Вынесен из client.ts отдельным модулем без зависимостей от axios и от DOM
 * именно чтобы его можно было покрыть юнит-тестами (тесты гоняются в node-окружении,
 * без jsdom) — логика здесь неочевидная, а цена ошибки высокая.
 *
 * Задача — не допустить параллельных обменов. Страница активности выпускает
 * восемь запросов сразу, и после истечения access-токена все восемь получают
 * 401 практически одновременно. Refresh-токен на сервере одноразовый: успешный
 * обмен отзывает предъявленный токен и выдаёт новый. Значит из восьми
 * параллельных обменов удался бы только первый, а остальные семь предъявили бы
 * уже отозванный токен — что сервер (справедливо) трактует как признак кражи и
 * в ответ обрывает вообще все сессии пользователя. То есть без разделяемого
 * промиса истечение токена приводило бы к разлогину вместо продления.
 */
export interface RefreshCoordinatorDeps<T> {
  /** Выполняет собственно обмен. Вызывается не чаще одного раза за «волну». */
  performRefresh: () => Promise<T>;
}

export interface RefreshCoordinator<T> {
  refresh: () => Promise<T>;
  /** Для тестов и диагностики: идёт ли обмен прямо сейчас. */
  isRefreshing: () => boolean;
}

export function createRefreshCoordinator<T>({ performRefresh }: RefreshCoordinatorDeps<T>): RefreshCoordinator<T> {
  let inFlight: Promise<T> | null = null;

  return {
    refresh() {
      // Все, кто пришёл во время идущего обмена, ждут его результат.
      if (inFlight) return inFlight;

      // Промис сбрасывается и при успехе, и при ошибке: следующее истечение
      // токена (через 15 минут) должно инициировать новый обмен, а не вернуть
      // давно завершившийся промис. При этом отказ обязан дойти до КАЖДОГО
      // ожидающего, поэтому возвращается общий промис, а не пересозданный.
      const current = performRefresh().finally(() => {
        if (inFlight === current) inFlight = null;
      });
      inFlight = current;
      return current;
    },
    isRefreshing: () => inFlight !== null,
  };
}
